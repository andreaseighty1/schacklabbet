import { build } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
await mkdir("supabase/dashboard", { recursive: true });
await build({
  entryPoints: ["supabase/functions/chess-room/index.ts"],
  outfile: "supabase/dashboard/chess-room.ts",
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  alias: { "chess.js": "npm:chess.js@1.4.0" },
  external: ["npm:*"],
  banner: {
    js: "// Generated by npm run prepare:multiplayer. Deploy as chess-room; keep Verify JWT enabled.",
  },
});
const migrations = [
  "202610220001_private_chess.sql",
  "202610220002_room_retention.sql",
];
await writeFile(
  "supabase/dashboard/setup.sql",
  (
    await Promise.all(
      migrations.map((file) => readFile(`supabase/migrations/${file}`, "utf8")),
    )
  ).join("\n\n"),
);
console.log(
  "PASS: ready-to-paste SQL and single-file Edge Function prepared without credentials.",
);
